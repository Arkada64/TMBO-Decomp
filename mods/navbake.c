#define NLEV ((int)(sizeof(NAV_LEVELS) / sizeof(NAV_LEVELS[0])))

static float KB[4] = { 1e30f, 0.25f, 16.0f, 0.75f };   /* no float literals in code (.lit4 is gp-relative) */
static NavHdr* nav;            /* loaded map of the current level, or 0 */
static NavNode* nodes;
static int navLevel = -1;

/* packs.c tmbr_LevelDbLoaded (level db stage, slot 0): read this level's map */
static int late = -1;          /* level whose map waits for the first game frame */
static void navRead(int level, int now);
void tmbr_NavLoad(int level) { navRead(level, 0); }
static void navRead(int level, int now)
{
    static char name[] = "\\PCAR\\ZN00.BIN;1";
    int i;
    late = -1;
    nav = 0; nodes = 0; navLevel = level;
    for (i = 0; i < NLEV && NAV_LEVELS[i].level != level; i++) ;
    if (i == NLEV) return;
    if (NAV_LEVELS[i].late && !now) {    /* PRISON / SUBURB: the point-file buffer is busy until the level is in */
        late = level;
        return;
    }
    name[9] = '0' + level / 10; name[10] = '0' + level % 10;
    ((u32*)NAV_LEVELS[i].addr)[0] = 0;
    fileRead(name, (void*)NAV_LEVELS[i].addr);
    if (((NavHdr*)NAV_LEVELS[i].addr)->magic != 0x3156414E) {     /* "NAV1" */
        scePrintf("TMBR nav: no map for level %d (%s)\n", level, name);
        return;
    }
    nav = (NavHdr*)NAV_LEVELS[i].addr;
    nodes = (NavNode*)(nav + 1);
    scePrintf("TMBR nav: level %d map, %d nodes, cell %d\n", level, nav->n, (int)nav->cell);
}

/* first game frame (nav.c tmbr_NavFrame): the late maps (point-file buffer) */
void tmbr_NavLateLoad(void)
{
    int lv = late;
    if (lv < 0 || lv != tmbr_levelIndex) return;
    scePrintf("TMBR nav: late load of level %d's map (point-file buffer)\n", lv);
    navRead(lv, 1);
}
int tmbr_NavBaked(void) { return nav && navLevel == tmbr_levelIndex; }
float tmbr_NavArrive(void) { return nav->cell * KB[3]; }   /* waypoint reached within 3/4 of a cell */

static void nodePos(int k, fvec* p)
{
    NavNode* n = &nodes[k];
    int gj = n->cell / nav->gw, gi = n->cell % nav->gw;
    p->x = nav->x0 + (float)gi * nav->cell + (float)(n->off & 15) * nav->step;
    p->y = nav->y0 + (float)gj * nav->cell + (float)(n->off >> 4) * nav->step;
    p->z = (float)n->z4 * KB[1];
    p->w = KB[1] - KB[1];
}
/* first node of a cell (nodes are sorted by cell), -1 when none */
static int cellFirst(u32 cell)
{
    int lo = 0, hi = (int)nav->n;
    while (lo < hi) {
        int mid = (lo + hi) >> 1;
        if (nodes[mid].cell < cell) lo = mid + 1; else hi = mid;
    }
    return lo < (int)nav->n && nodes[lo].cell == cell ? lo : -1;
}
static int iabs(int a) { return a < 0 ? -a : a; }
/* the node of `cell` nearest to height z4 (z * 4) */
static int cellNode(u32 cell, int z4)
{
    int k = cellFirst(cell), best = -1, bd = 0x7FFFFFFF;
    if (k < 0) return -1;
    for (; k < (int)nav->n && nodes[k].cell == cell; k++) {
        int d = iabs(nodes[k].z4 - z4);
        if (d < bd) { bd = d; best = k; }
    }
    return best;
}
static const signed char DJ[8] = { 0, 1, 1, 1, 0, -1, -1, -1 }, DI[8] = { 1, 1, 0, -1, -1, -1, 0, 1 };
static int neighbour(int k, int d)
{
    int gj = nodes[k].cell / nav->gw + DJ[d], gi = nodes[k].cell % nav->gw + DI[d];
    if (gj < 0 || gi < 0 || gj >= nav->gh || gi >= nav->gw) return -1;
    return cellNode((u32)(gj * nav->gw + gi), nodes[k].z4);
}
/* nearest node to a world position: its cell and the 8 around it, by distance + 4 x height difference */
static int nearest(fvec* p)
{
    int gi = (int)((p->x - nav->x0) / nav->cell), gj = (int)((p->y - nav->y0) / nav->cell), r, dj, di, best = -1;
    float bd = KB[0];
    for (r = 0; r <= 1; r++)
        for (dj = -r; dj <= r; dj++)
            for (di = -r; di <= r; di++) {
                int k, cj = gj + dj, ci = gi + di;
                if (cj < 0 || ci < 0 || cj >= nav->gh || ci >= nav->gw) continue;
                for (k = cellFirst((u32)(cj * nav->gw + ci)); k >= 0 && k < (int)nav->n && nodes[k].cell == (u32)(cj * nav->gw + ci); k++) {
                    fvec q; float d, dz;
                    nodePos(k, &q);
                    dz = q.z - p->z; if (dz < 0) dz = -dz;
                    d = (q.x - p->x) * (q.x - p->x) + (q.y - p->y) * (q.y - p->y) + KB[2] * dz * dz;
                    if (d < bd) { bd = d; best = k; }
                }
            }
    return best;
}

/* ---- A* with a hash of visited nodes ---- */
#define HB 4096                 /* hash slots (power of two) */
#define BUDGET 2500             /* node expansions per plan */
typedef struct { int node; int g; short parent; char closed; char pad; } Slot;
static Slot hs[HB];
static short heap[HB];
static int hn, fcost[HB];
static int slotOf(int node, int make)
{
    u32 h = ((u32)node * 2654435761u) >> 20;
    int i;
    for (i = 0; i < HB; i++, h = (h + 1) & (HB - 1)) {
        if (hs[h].node == node) return (int)h;
        if (hs[h].node < 0) {
            if (!make) return -1;
            hs[h].node = node; hs[h].g = 0x7FFFFFFF; hs[h].parent = -1; hs[h].closed = 0;
            return (int)h;
        }
    }
    return -1;
}
static void hpush(int s)
{
    int i = hn++, p;
    while (i > 0 && fcost[heap[p = (i - 1) / 2]] > fcost[s]) { heap[i] = heap[p]; i = p; }
    heap[i] = (short)s;
}
static int hpop(void)
{
    int top = heap[0], last = heap[--hn], i = 0, k;
    while ((k = 2 * i + 1) < hn) {
        if (k + 1 < hn && fcost[heap[k + 1]] < fcost[heap[k]]) k++;
        if (fcost[heap[k]] >= fcost[last]) break;
        heap[i] = heap[k]; i = k;
    }
    heap[i] = (short)last;
    return top;
}
static int hcost(int a, int b)       /* octile distance in cells, x10 */
{
    int dj = iabs((int)(nodes[a].cell / nav->gw) - (int)(nodes[b].cell / nav->gw));
    int di = iabs((int)(nodes[a].cell % nav->gw) - (int)(nodes[b].cell % nav->gw));
    return 10 * (dj + di) - 6 * (dj < di ? dj : di);
}

/* plan from `from` to `to`; fills up to maxwp waypoints (the first is the step after the start node).
 * Returns the number of waypoints, 0 = no map / no node near either end / no progress possible. */
int tmbr_NavBakedPlan(fvec* from, fvec* to, fvec* wp, int maxwp, int* full)
{
    static short path[512];
    int a, b, i, s, best, bestH, exp = 0, n = 0, k;
    if (!tmbr_NavBaked()) return 0;
    a = nearest(from); b = nearest(to);
    if (a < 0 || b < 0) return 0;
    for (i = 0; i < HB; i++) hs[i].node = -1;
    hn = 0;
    s = slotOf(a, 1); hs[s].g = 0; fcost[s] = hcost(a, b); hpush(s);
    best = s; bestH = fcost[s];
    *full = 0;
    while (hn && exp < BUDGET) {
        int c = hpop(), node, d;
        if (hs[c].closed) continue;
        hs[c].closed = 1; exp++;
        node = hs[c].node;
        if (node == b) { best = c; *full = 1; break; }
        if (hcost(node, b) < bestH) { bestH = hcost(node, b); best = c; }
        for (d = 0; d < 8; d++) {
            int m, ms, g;
            if (!(nodes[node].links & (1 << d))) continue;
            m = neighbour(node, d);
            if (m < 0) continue;
            ms = slotOf(m, 1);
            if (ms < 0 || hs[ms].closed) continue;
            g = hs[c].g + ((d & 1) ? 14 : 10);
            if (g >= hs[ms].g) continue;
            hs[ms].g = g; hs[ms].parent = (short)c;
            fcost[ms] = g + hcost(m, b);
            if (hn < HB) hpush(ms);
        }
    }
    /* walk back */
    for (k = best; k >= 0 && n < 512; k = hs[k].parent) path[n++] = (short)k;
    if (n < 2) return 0;
    /* path[n-1] is the start node: emit from the next one on, skipping straight runs */
    k = 0;
    for (i = n - 2; i >= 0 && k < maxwp; i--) {
        if (i > 0 && i < n - 2) {
            int p0 = hs[path[i + 1]].node, p1 = hs[path[i]].node, p2 = hs[path[i - 1]].node;
            int d1 = (int)nodes[p1].cell - (int)nodes[p0].cell, d2 = (int)nodes[p2].cell - (int)nodes[p1].cell;
            if (d1 == d2 && iabs(nodes[p2].z4 - nodes[p0].z4) < 8) continue;   /* same direction, same floor */
        }
        nodePos(hs[path[i]].node, &wp[k]);
        k++;
    }
    return k;
}
