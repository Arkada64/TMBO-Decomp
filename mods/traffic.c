/* destroyed cars: the game blows them up but nothing removed them (retail's gameCheckNumFodder only walks the
 * 8 slots). 2 s after health reaches 0 the car is hidden and leaves the update / collisions; 30 s later it comes
 * back repaired on a new street point. */
extern void hierSetSwitchT(void* sw, int i) __asm__("hierSetSwitch__FP11_hierswitchi");
static void respawn(char* v)
{
    int q;
    static const int sws[4] = { 0x2044, 0x2048, 0x2050, 0x2054 };
    *(float*)(v + 0x404) = *(float*)(v + 0x400);
    for (q = 0; q < 4; q++) if (F(v, sws[q])) hierSetSwitchT((void*)F(v, sws[q]), 0);
    F(v, 0x590) = 3;
    /* no fodderInit here: it re-runs the full vehicle init (func_001D6F78) on a live car and froze the game
     * right after a respawn; the car keeps its driver and street state, only health / looks are reset */
    if (F(v, 0x202C)) hierSetCsDrawMe((void*)F(v, 0x202C), 1);
    hierSetCsDrawMe((void*)F(v, 0x2028), 1);
}
static void destructionStep(int j)
{
    char* v = cars + j * VSIZE;
    if (deadT[j] == 0) {
        if (F(v, 0x590) && *(float*)(v + 0x404) <= 0.0f) deadT[j] = 1;
        return;
    }
    deadT[j]++;
    if (deadT[j] == 120) {                    /* 2 s: gone */
        F(v, 0x590) = 0;
        hierSetCsDrawMe((void*)F(v, 0x2028), 0);
        if (F(v, 0x202C)) hierSetCsDrawMe((void*)F(v, 0x202C), 0);
        if (TRAFFIC_DBG) scePrintf("TMBR traffic: car %d destroyed\n", j);
    }
    if (deadT[j] >= 120 + 1800 && !netIsHost(D_003156C0)) deadT[j] = 120 + 1800 - 1;   /* clients wait for the host */
    if (deadT[j] >= 120 + 1800) { respawn(v); deadT[j] = 0; if (TRAFFIC_DBG) scePrintf("TMBR traffic: car %d back\n", j); }
}

static int fb(float f) { union { float f; int i; } u; u.f = f; return u.i; }

/* Car-to-car collisions with traffic. collisCsToCsCollision (collis.s, 0x121B9C) asks IsInteractiveAVehicle
 * which vehicle owns the cs it hit; that only scans the 8 slots, so cars drove through traffic. This version
 * (hooked at that one call; the game's other 56 callers keep the 8-slot answer, since their per-player arrays
 * can't take a traffic index) also finds traffic cars, as an index from game (cars sit a whole number of
 * vehicles away from it). */
int tmbr_IsVehicleOrTraffic(char* g, int ia, int* out)
{
    int i;
    for (i = 0; i < 8; i++) {
        char* v = g + i * VSIZE;
        if (F(v, 0x590) && F(v, 0x20FC) == ia) { *out = i; return 1; }
    }
    for (i = 0; i < ncars; i++) {
        char* v = cars + i * VSIZE;
        if (F(v, 0x590) && F(v, 0x20FC) == ia) { *out = (int)(v - g) / VSIZE; return 1; }
    }
    return 0;
}

/* vehicle-vehicle hit (func_00121D10 calls func_00122AF0(v, side, other, info) once per car): hits on or by a
 * traffic car keep their push but do no damage. func_00122AF0 only damages when one of the two is a human
 * (+0x590 == 1), so both kinds are hidden for the call. */
extern void collideHit(char* v, int side, char* other, void* info) __asm__("func_00122AF0");
void tmbr_CollideHit(char* v, int side, char* other, void* info)
{
    char* g = D_004FA030;
    int ka, kb;
    if ((v >= g && v < g + 8 * VSIZE) && (other >= g && other < g + 8 * VSIZE)) {
        collideHit(v, side, other, info);
        return;
    }
    ka = F(v, 0x590); kb = F(other, 0x590);
    F(v, 0x590) = 3; F(other, 0x590) = 3;
    collideHit(v, side, other, info);
    F(v, 0x590) = ka; F(other, 0x590) = kb;
}

extern int tmbr_Opt(int bit);   /* bots.c: lobby options in the game info */
void tmbr_TrafficUpdate(void)
{
    int j;
    if (doneSerial != tmbr_levelSerial) {
        doneSerial = tmbr_levelSerial;
        if (!tmbr_Opt(1)) { ncars = 0; scePrintf("TMBR traffic: off (lobby option, default)\n"); }   /* bots.c lobby option */
        else setup();
    }
    if (ncars && netIsHost(D_003156C0) && ++syncTick >= SYNC_EVERY) { syncTick = 0; syncSend(); }
    for (j = 0; j < ncars; j++) destructionStep(j);
    for (j = 0; j < ncars; j++) {
        char* v = cars + j * VSIZE;
        if (!F(v, 0x590)) continue;
        vehicleUpdate(v);
        if (!F(v, 0x2158) && (F(v, 0x1D0) || F(v, 0x1D4))) {
            /* physics: without this a car only moved in cheap (off-screen) mode and froze on screen */
            phys1(v); phys2(v); phys3(v); phys4(v); phys5(v); phys6(v);
            if (F(v, 0x1A78)) { vehicleSetCsMat(v); phys7(v); }
            if (!F(v, 0x1A68)) {
                int* s4 = (int*)(F(v, 0x790) + 0x10);
                int* cs = (int*)(F(v, 0x2028) + 0x10);
                int q;
                for (q = 0; q < 4; q++) ((int*)(v + 0x280))[q] = s4[q];
                for (q = 0; q < 16; q++) ((int*)(v + 0x90))[q] = s4[4 + q];
                for (q = 0; q < 4; q++) ((int*)(v + 0x270))[q] = cs[q];
                for (q = 0; q < 16; q++) ((int*)(v + 0x50))[q] = cs[4 + q];
            }
            suspUpdate(v);
            vehicleSetCsMat(v);
            vehicleAfterNewPos(v);
        } else {
            /* cheap mode (off screen): the drivers move the vehicle, not its cs. MINIBURB's street cars stayed
             * at the origin (cs never set), so never on screen, so never out of cheap mode. */
            vehicleSetCsMat(v);
        }
    }
    if (TRAFFIC_DBG && ncars && dbgTick % 600 == 599)
        scePrintf("TMBR traffic sync: host %d, sent %d, received %d\n", netIsHost(D_003156C0), syncSent, syncRecv);
    if (TRAFFIC_DBG && ncars && ++dbgTick % 120 == 0)
        for (j = 0; j < ncars && j < 4; j++) {
            char *v = cars + j * VSIZE, *cs = (char*)F(v, 0x2028);
            scePrintf("TMBR trafdbg %d: kind %d hidden %d b485 %d b488 %d t2150 %d own %d hw %x st %x cs %x [%d %d %d] pos %08x %08x v1D0 %08x %08x drv20 %08x %08x spd %08x pad %d%d%d\n",
                j, F(v, 0x590), F(v, 0x2158), *(unsigned char*)(v + 0x485), *(unsigned char*)(v + 0x488), F(v, 0x2150),
                F(v, 0x20B4), F(v, 0x201C), F(v, 0x2020), (u32)cs, cs ? cs[0xC] : -1, cs ? cs[0xD] : -1, cs ? cs[0xE] : -1,
                cs ? fb(*(float*)(cs + 0x10)) : 0, cs ? fb(*(float*)(cs + 0x14)) : 0, F(v, 0x1D0), F(v, 0x1D4),
                F(v, 0x2020) ? F(F(v, 0x2020), 0x20) : 0, F(v, 0x2020) ? F(F(v, 0x2020), 0x24) : 0, fb(*(float*)(v + 0x2D4)),
                *(unsigned char*)(v + 0x598), *(unsigned char*)(v + 0x59A), *(unsigned char*)(v + 0x59D));
        }
}
