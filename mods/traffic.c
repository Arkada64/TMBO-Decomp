/* TMB-Reloaded mod: traffic ("fodder" cars) in online maps, phase 1 (spawn, drive, draw, take weapon hits).
 * Online keeps the traffic code and (except SUBURB) the traffic models in the level db, but its TheGame has
 * only the 8 player vehicle slots (game+i*0x31B0, other fields right after) and no fodder driver arrays
 * (online SetFodderCar would put them over the camera at game+0x27780). So the cars get their own array.
 * Setup runs on the first game frame of each level (after online's InitializeFodderCars, func_0013AB90,
 * which finds no traffic): a port of retail FodderParse/AddFodder/InitializeFodderCars/SetFodderCar over:
 *   - the level's fodder model nodes (absolute addresses, generated offline: traffic_nodes.h);
 *   - vehicles (0x31B0 each) + drivers in free memory of that level, placed a whole number of vehicles away
 *     from game, so "game + index*0x31B0" means the right car for code that works with vehicle indices.
 * Cars are type-2 interactives: weapon hits reach fodderTakeHit through Interactives::DispatchHit.
 * Each frame (tmbr_TrafficUpdate, called from tmbr_CameraUpdate after the game's vehicle loops):
 * vehicleUpdate + suspension + cs matrix + after-new-position for every active car. FREEWAY's highway cars
 * are run by the TrafficDirector, which the game already updates on highway levels.
 * Not yet: car-to-car collisions (func_0013CEE0 only walks the 8 slots), sound, network sync. */
typedef unsigned int u32;
typedef struct { int level; const unsigned int* nodes; int n; unsigned int mem, memEnd; } FodderLevel;
extern const FodderLevel tmbr_fodderLevels[]; /* traffic_nodes.c, generated by TMB Decomp/fodnodes.py */
extern const int tmbr_numFodderLevels;

extern char* D_004FA030;              /* game */
extern void* D_004FA034;              /* interactives */
extern int D_004FAE38;                /* online fixed slot layout */
extern int D_004FB480, D_004FB484, D_004FB488; /* max/new/highway fodder counts */
extern int tmbr_levelSerial, tmbr_levelIndex;  /* set by packs.c on every level load */
extern void* memset(void* p, int c, unsigned int n);
extern int scePrintf(const char* fmt, ...);
extern int interactivesAdd(void* in, int type, void* obj, void* pos, int size) __asm__("func_0014F070");
extern void attachInit(char* v) __asm__("func_0010AED0");
extern void attachAdd(char* v, int sub, void* h) __asm__("attachAdd__7VehicleiP9_hierhead");
extern void hierCsPtLightMe(void* cs, int on) __asm__("hierCsPtLightMe__FP3_csi");
extern void hierSetCsDrawMe(void* cs, int on) __asm__("hierSetCsDrawMe__FP3_csUc");
extern void* tmbr_FodderCs(void* h);  /* traffic.s: cs for a fodder model (own pool) */
extern void fodderDriverInit(void* drv, void* points) __asm__("init__12FodderDriverP15AttractorPoints");
extern void fodderInit(char* v, char* game) __asm__("func_001343D8");
extern void highwayFodderInit(char* v, char* game) __asm__("func_00133EF0");
extern void trafficDirectorInit(void* td, void* hw, void* first, int n) __asm__("func_001B0688");
extern void vehicleUpdate(char* v) __asm__("func_001DC760");
extern void suspUpdate(char* v) __asm__("func_001AA3B8");
extern void vehicleSetCsMat(char* v) __asm__("func_001E0230");
extern void vehicleAfterNewPos(char* v) __asm__("func_001DCD48");

#define VSIZE 0x31B0
#define MAXCARS 32       /* retail allows 33; traffic.s has a 32-entry cs pool (LOOP has 32 cars) */
#define F(v, off) (*(int*)((v) + (off)))
static int doneSerial = -1;
static char* cars;       /* traffic vehicle array */
static int ncars;

static void addFodder(char* v, void* cs, int name, int nameIndex)
{
    u32* head;
    int idx;
    F(v, 0x20F0) = nameIndex;
    idx = interactivesAdd(D_004FA034, 2, v, (char*)cs + 0x10, VSIZE);
    F(v, 0x20F4) = name;
    F(v, 0x20FC) = idx;
    if (name < 0xBB7) {
        int rel = name - 2000;
        F(v, 0x20F8) = (rel >= 0 ? rel : rel + 31) >> 4;
    }
    F(v, 0x2028) = (int)cs;
    attachInit(v);
    head = *(u32**)cs;
    *head = (*head & 0x3FFFF) | ((u32)name << 18);
    *head = (*head & 0xFFFC007F) | ((idx & 0x7FF) << 7);
    hierCsPtLightMe(cs, 1);
    hierSetCsDrawMe(cs, 0);
    F(v, 0x590) = 0;
}

static void setup(void)
{
    char* game = D_004FA030;
    const unsigned int* nodes = 0;
    int n = 0, i, j, k, type, ngroups = 0, nhw = 0, points, active, savedCount;
    u32 mem = 0, memEnd = 0, r;
    char *drv, *hwdrv;
    static int gHead[64], gName[64], gFirst[64], gLast[64], order[64];
    ncars = 0;
    if (!D_004FAE38) return;
    for (i = 0; i < tmbr_numFodderLevels; i++)
        if (tmbr_fodderLevels[i].level == tmbr_levelIndex) {
            nodes = tmbr_fodderLevels[i].nodes; n = tmbr_fodderLevels[i].n;
            mem = tmbr_fodderLevels[i].mem; memEnd = tmbr_fodderLevels[i].memEnd;
        }
    if (!nodes) return;
    type = F(game, 0x9FCA0);
    points = F(game, 0x34890 + 0x248);
    /* group the nodes like retail FodderParse: a car per base node (sub 0), attachments follow it */
    for (i = 0; i < n; i++) {
        u32 id = *(u32*)nodes[i] >> 18;
        int rel = (int)id - 2000, sub, base;
        if (id < 0x401 || id >= 0xBB8) {
            scePrintf("TMBR traffic: node %d at %x has id %d, level data differs, no traffic\n", i, nodes[i], id);
            return;
        }
        sub = rel - ((rel >= 0 ? rel : rel + 31) >> 5) * 32;
        base = id - sub;
        if (sub == 0) {
            if (ngroups == 64) break;
            gHead[ngroups] = i; gName[ngroups] = base; gFirst[ngroups] = i + 1; gLast[ngroups] = i + 1;
            ngroups++;
        } else {
            for (k = ngroups - 1; k >= 0 && gName[k] != base; k--) ;
            if (k >= 0 && k == ngroups - 1) gLast[k] = i + 1;
        }
    }
    /* highway cars first on highway levels (the TrafficDirector takes a contiguous run) */
    k = 0;
    for (i = 0; i < ngroups; i++) if (type == 2 && gName[i] < 0x8F0) order[k++] = i;
    nhw = k;
    for (i = 0; i < ngroups; i++) if (!(type == 2 && gName[i] < 0x8F0)) order[k++] = i;
    if (ngroups > MAXCARS) ngroups = MAXCARS;
    if (nhw > ngroups) nhw = ngroups;
    /* memory: vehicles a whole number of VSIZE from game, then the drivers */
    r = (mem - (u32)game) % VSIZE;
    cars = (char*)(mem + (VSIZE - r) % VSIZE);
    drv = cars + ngroups * VSIZE;
    hwdrv = drv + MAXCARS * 0x70;
    if ((u32)(hwdrv + MAXCARS * 0x30) > memEnd) {
        scePrintf("TMBR traffic: not enough memory\n");
        return;
    }
    memset(cars, 0, (u32)(hwdrv + MAXCARS * 0x30) - (u32)cars);
    for (j = 0; j < ngroups; j++) {
        int g = order[j], same = 0;
        char* v = cars + j * VSIZE;
        for (k = 0; k < j; k++) if (gName[order[k]] == gName[g]) same++;
        addFodder(v, tmbr_FodderCs((void*)nodes[gHead[g]]), gName[g], same);
        for (i = gFirst[g]; i < gLast[g]; i++) {
            u32 id = *(u32*)nodes[i] >> 18;
            int sub = (int)id - gName[g];
            if (id < 0xBB7 && sub > 0 && sub < 32) attachAdd(v, sub, (void*)nodes[i]);
        }
    }
    ncars = ngroups;
    /* InitializeFodderCars + SetFodderCar */
    savedCount = F(game, 0x9FCB8);
    F(game, 0x9FCB8) = ncars;                   /* fodderInit spreads the start points over this */
    active = 0;
    for (j = 0; j < ncars; j++) {
        char* v = cars + j * VSIZE;
        int hw = j < nhw;
        if (!hw && points <= 0) continue;      /* no street points loaded: fodderInit would divide by 0 */
        F(v, 0x2104) = (int)((u32)(v - game) / VSIZE);
        F(v, 0x2100) = j;
        F(v, 0x2010) = 0; F(v, 0x2014) = 0; F(v, 0x2018) = 0;
        if (hw) {
            F(v, 0x2020) = 0;
            F(v, 0x201C) = (int)(hwdrv + j * 0x30);
            highwayFodderInit(v, game);
        } else {
            F(v, 0x201C) = 0;
            F(v, 0x2020) = (int)(drv + j * 0x70);
            fodderDriverInit(drv + j * 0x70, game + 0x34890);
            fodderInit(v, game);
        }
        if (F(v, 0x202C)) hierSetCsDrawMe((void*)F(v, 0x202C), 1);
        active++;
    }
    F(game, 0x9FCB8) = savedCount;
    D_004FB480 = active;
    D_004FB488 = nhw;
    D_004FB484 = type == 2 ? nhw : active;
    if (type == 2 && nhw > 0)
        trafficDirectorInit(game + 0x30510, game + 0x2BC30, cars, nhw);
    scePrintf("TMBR traffic: level %d type %d: %d cars (%d highway), %d active, street points %d, players %d, cars at %p\n",
        tmbr_levelIndex, type, ncars, nhw, active, points, F(game, 0x9FCAC), cars);
}

void tmbr_TrafficUpdate(void)
{
    int j;
    extern void tmbr_PackWatch(void);
    tmbr_PackWatch();
    if (doneSerial != tmbr_levelSerial) {
        doneSerial = tmbr_levelSerial;
        setup();
    }
    for (j = 0; j < ncars; j++) {
        char* v = cars + j * VSIZE;
        if (!F(v, 0x590)) continue;
        vehicleUpdate(v);
        if (!F(v, 0x2158)) {
            suspUpdate(v);
            vehicleSetCsMat(v);
            vehicleAfterNewPos(v);
        }
    }
}
