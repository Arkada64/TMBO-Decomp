def _swap(r):  # rows 4-7: halves of each 8-group swapped relative to rows 0-3 (+128)
    out=[]
    for g in range(0,32,8):
        grp=r[g:g+8]; out+= [x+128 for x in grp[4:]]+[x+128 for x in grp[:4]]
    return out
CT4=_c4+[_swap(r) for r in _c4]
CT4=CT4+[[v+256 for v in r] for r in CT4]
def ct32_word(x,y): return BT32[(y>>3)&3][(x>>3)&7]*64+CT32[y&7][x&7]
def t8_byte(x,y): return BT8[(y>>4)&3][(x>>4)&7]*256+CT8[y&15][x&15]
def t4_nib(x,y): return BT4[(y>>4)&7][(x>>5)&3]*512+CT4[y&15][x&31]
def mem_from_ct32(data,w,h):
    """write a w x h PSMCT32 rect (row-major words) at block 0, single page (w<=64,h<=32)"""
    words=np.frombuffer(bytes(data[:w*h*4]),np.uint32)
    mem=np.zeros(2048,np.uint32)
    for y in range(h):
        for x in range(w): mem[ct32_word(x,y)]=words[y*w+x]
    return mem.view(np.uint8)
def read_t8(mem,w,h):
    return np.array([mem[t8_byte(x,y)] for y in range(h) for x in range(w)],np.uint8)
def read_t4(mem,w,h):
    out=np.empty(w*h,np.uint8)
    for y in range(h):
        for x in range(w):
            n=t4_nib(x,y); b=mem[n>>1]; out[y*w+x]=(b>>4) if n&1 else (b&15)
    return out
