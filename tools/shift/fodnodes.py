"""
Online traffic (fodder) model nodes per level, exactly as the level loader callback would see them (traversal
order), as absolute addresses in the loaded level (0x980000 + offset). Writes mods/traffic_nodes.h for the
traffic mod (a level only qualifies if it has fodder nodes) and prints a summary.
"""
import collections
from ngpdb import get
from ngptrav import visit
LEVELS = {"SUBURB": 0, "FREEWAY": 2, "CITY": 5, "LOOP": 6, "MINICITY": 17, "MINIBURB": 18}
out = ["/* generated by TMB Decomp/fodnodes.py: online level traffic (fodder) model nodes, loader order */"]
tables = []
for lvl, idx in LEVELS.items():
    v = visit(get("online", lvl, "NGP"))
    nodes = [(0x980000 + o, i1) for o, op, i1, i2 in v if 0x401 <= i1 < 0xBB8]
    if not nodes:
        print(f"{lvl}: no fodder nodes online"); continue
    heads = [(a, i) for a, i in nodes if (i - 2000) % 32 == 0]
    hw = [i for a, i in heads if i < 0x8F0]
    names = collections.Counter(i for a, i in heads)
    print(f"{lvl}: {len(nodes)} nodes, {len(heads)} cars ({len(hw)} highway-range < 2288), ids {min(i for a, i in nodes)}..{max(i for a, i in nodes)}, models {len(names)}")
    out.append(f"const unsigned int fod_{lvl.lower()}[] = {{")
    out += [f"    0x{a:08X}, /* {i} */" for a, i in nodes]
    out.append("};")
    tables.append((idx, lvl, len(nodes)))
# free memory for the traffic vehicles/drivers per level: the largest free area not used by a pack
import json, os, mkblobs
def region(lvl):
    ar = [(a, cap) for a, cap, nm in mkblobs.areas(lvl)]
    lay = "/mnt/c/Users/Ark/Desktop/TMB Decomp/packs/"
    used = []
    for f in os.listdir(lay):
        if f.endswith(".layout.json"):
            d = json.load(open(lay + f))
            if d["level"] == lvl: used += [(int(a, 16), s) for fn, a, s in d["blobs"]]
    best = None
    for a, cap in ar:
        end = a + cap
        for ua, us in used:
            if a <= ua < end: a = max(a, ua + us)       # blobs sit at the area start
        a = (a + 127) & ~127
        if best is None or end - a > best[1] - best[0]: best = (a, end)
    return best
out.append("typedef struct { int level; const unsigned int* nodes; int n; unsigned int mem, memEnd; } FodderLevel;")
out.append("const FodderLevel tmbr_fodderLevels[] = {")
for idx, lvl, n in tables:
    a, e = region(lvl)
    print(f"  {lvl}: traffic memory 0x{a:X}..0x{e:X} ({(e - a) // 1024} KB)")
    out.append(f"    {{ {idx}, fod_{lvl.lower()}, {n}, 0x{a:X}, 0x{e:X} }}, /* {lvl} */")
out.append("};")
out.append(f"const int tmbr_numFodderLevels = {len(tables)};")
open("/mnt/c/Users/Ark/Desktop/TMB Decomp/mods/traffic_nodes.c", "w").write("\n".join(out) + "\n")
